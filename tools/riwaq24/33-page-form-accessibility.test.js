const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '../..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
test('independent Riwaq page-form accessibility fixes', () => {
  const visits = read('branch-visits-new/index.html');
  assert.match(visits, /aria-labelledby="criterion-\$\{esc\(template\.id\)\}"/);
  assert.match(visits, /data-score="10" aria-pressed="false"/);
  assert.match(visits, /aria-pressed', 'true'/);
  assert.match(visits, /data-note aria-label="ملاحظة معيار \$\{esc\(template\.title\)\}"/);
  assert.match(visits, /data-assignee[^>]+aria-label="المسؤول عن إجراء المعيار/);
  const daily = read('daily-report/index.html');
  assert.match(daily, /<label for="reportDate"/);
  assert.match(daily, /<label for="shiftType"/);
  assert.match(daily, /class="bg-primary text-on-primary[^\"]*" id="submitReportBtn"/);
  const inventory = read('inventory-requests/index.html');
  assert.match(inventory, /bg-\[#075e54\]/);
  assert.match(inventory, /setAttribute\('aria-label', `حذف الصنف \$\{index \+ 1\}`\)/);
  const templates = read('manage-templates/index.html');
  assert.match(templates, /template-filter-empty/);
  assert.match(templates, /لا توجد قوالب مطابقة للبحث أو التكرار المحدد/);
  const mine = read('my-checklist/index.html');
  assert.match(mine, /aria-labelledby="task-title-\$\{taskId\}"/);
  assert.match(mine, /for="task-note-\$\{taskId\}"/);
  assert.match(mine, /class="evidence-input sr-only"/);
  const supervisor = read('supervisor-checklist/index.html');
  assert.match(supervisor, /aria-labelledby="task-title-\$\{escHtml\(item\.id\)\}"/);
  assert.match(supervisor, /role="status" aria-live="polite"/);
  const weekly = read('assets/weekly-report-core.js');
  assert.match(weekly, /aria-labelledby="manager-note-label-/);
  assert.match(weekly, /id="manager-note-/);
});
